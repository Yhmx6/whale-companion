# ---- VLM 生成尺度锚点 -----------------------------------------------------

ANCHOR_SYS = (
    "你是一个图像标注助手。用户会给你一张室内照片，以及他打算把一个约 40 厘米高的"
    "Q版玩偶放在画面里的哪个位置。你的任务是输出一句中文，说明这个玩偶放好之后，"
    "它的头顶大概与画面里哪个已有物体的哪个部位齐平。\n"
    "要求：\n"
    "1. 必须引用画面里真实存在的物体，具体到某个部位（例如「柜门中间那道横缝」"
    "「椅背的一半」「坐垫上的荷叶边」）；\n"
    "2. 不要使用百分比、像素、厘米等单位；\n"
    "3. 只输出一句话，不要解释、不要分点、不要引号。"
)


def vlm_scale_anchor(scene_path: str, placement: str) -> str:
    """调用 VLM 生成尺度锚点句。失败时返回空串，由调用方回退到人工锚点。"""
    from api.ark import ENV, _post, image_path_to_data_uri

    model = ENV.get("ARK_VLM_MODEL", "doubao-seed-2-1-lite-260915")
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": ANCHOR_SYS},
            {"role": "user", "content": [
                {"type": "image_url",
                 "image_url": {"url": image_path_to_data_uri(scene_path, max_side=1024)}},
                {"type": "text",
                 "text": f"这个玩偶要放在：{placement}。请给出尺度锚点句。"},
            ]},
        ],
        "temperature": 0.2,
        "max_tokens": 160,
    }
    status, resp = _post("/chat/completions", payload, timeout=90)
    if status != 200:
        print(f"  [VLM 失败 {status}] {str(resp)[:200]}")
        return ""
    try:
        txt = resp["choices"][0]["message"]["content"].strip()
    except (KeyError, IndexError):
        return ""
    return txt.strip("「」\"' \n")


