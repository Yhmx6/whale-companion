            "2. 角色坐在家具上，所以座面会在她身下压出一点凹陷，"
            "她也会在座面上投下淡淡的接触阴影，这层阴影必须画出来；\n",
            "3. 角色的手要自然：撑在身侧的手整只平贴，不要画出分开的手指和指关节；\n",
            "4. 角色的形象必须与设定图一致：蓝色渐变长发、深蓝色鲸鱼耳、藏青女仆裙、"
            "白色荷叶边围裙及围裙上的鲸鱼图案、身后深蓝色鲸尾、深蓝色小皮鞋；\n",
            "5. 不要出现多余的手指、多余的肢体、断裂的肢体；\n",
