"""S2 提示词构建器（v2 定稿）——把实验结论固化成生产代码。

## 三条定稿结论（来自 5 案例 × 多轮实测）

1. **体型必须显式量化，不能只说"Q版"**。只说 Q 版，模型会画成 6-7 头身的美少女，
   腿自然就长了。量化成"2 到 2.5 头身""大腿加小腿不超过头部高度的 1.5 倍"才生效。
2. **尺度锚点必须用参照物，不能用画面百分比**。百分比不转化为场景尺度感；
   "头顶只到柜门中间那道横缝"才有效。
3. **"禁止白描边"的提示词无效**（A/B 已证伪，两组都有描边）。描边只能靠
   程序化 defringe 或环带二次融合解决，不要浪费提示词预算。

## 一个附带发现

参照物锚点句是最难自动化的部分——它要求"看懂画面里有什么、她该跟哪个部位齐平"。
这正是 VLM 的用武之地，而且比"用 VLM 估光"更有价值（估光有深度法线这条纯 CPU 的路）。
`vlm_scale_anchor()` 就是用 VLM 生成这句话，输入照片 + 落点描述，输出一句可直接
塞进提示词的中文。
"""

