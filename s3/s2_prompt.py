#
# 与单人模式的三个本质差异，都来自"她要和人发生物理接触"：
#   1. 位置不再由框决定，而是由人物的身体部位决定（手臂、肩膀、脸侧、腿上）；
#   2. **接触暗部要由模型生成**——影子落在人的衣服上，不是地面上。
#      单人模式里我们禁止模型画地面投影，这里的指令正好相反，因为接触面是衣服；
#   3. 遮挡关系必须正确：她挡在人前面的手要盖住衣服，在人后面的手要被身体挡住。
#
# 缩放：贴贴模式下**不做 S2.5 尺度归一**。她要多大由人物身体决定，
# 用框去强行拉伸会把"挂件感"变成"巨人贴脸"。

