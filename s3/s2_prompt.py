            "7. 画面里**恰好一个**角色。只有一个她，不要画出第二个、不要画成双胞胎、"
            "不要出现倒影或镜像；不要文字、水印、边框；\n",
            "8. 角色要显得小巧可爱，像玩偶一样坐在家具上，不要画成与家具同高的成年人。\n",
